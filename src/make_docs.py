#!/usr/bin/env python3
"""Auto-generate the data dictionary, dataset card, environment lock and
reproduction command sheet from measured results.  Never hand-edit numbers.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import platform
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import POST_HOC_FIELDS, SCHEMA  # noqa: E402

ROLES = {
    "Date received": ("ISO-8601 timestamp", "submission-time; temporal split key",
                      "parse to YYYY-MM-DD; keep whole days in one fold"),
    "Product": ("categorical", "submission-time feature / grouping key",
                "keep as category; report subgroup mix"),
    "Sub-product": ("categorical", "submission-time feature", "keep; missing -> explicit level"),
    "Issue": ("categorical", "DECLARED TARGET (multi-class)",
              "rare classes (<20 train examples) collapsed to __OTHER__"),
    "Sub-issue": ("categorical", "submission-time feature", "keep"),
    "Consumer complaint narrative": ("free text", "DECLARED INPUT FEATURE; PII risk",
                                     "whitespace normalised, truncated to 2500 chars, "
                                     "redacted before any external call"),
    "Company public response": ("categorical", "POST-HOC -- excluded from features",
                                "label-side only; never in a feature matrix"),
    "Company": ("categorical", "submission-time feature / overlap audit key",
                "report train/test company overlap"),
    "State": ("categorical", "submission-time feature / subgroup axis", "keep"),
    "ZIP code": ("string", "quasi-identifier; subgroup audit only",
                 "XXXXX / NNNXX recorded as 'masked', NOT an error"),
    "Tags": ("categorical", "sensitive attribute (servicemember / older American)",
             "audit only; never a predictor"),
    "Submitted via": ("categorical", "submission-time feature (near-constant)",
                      "check coverage/variance before keeping"),
    "Date sent to company": ("ISO-8601 timestamp", "POST-HOC -- excluded from features",
                             "label-side only"),
    "Company response to consumer": ("categorical", "POST-HOC outcome",
                                     "label-side only; 'In progress' is not a final label"),
    "Timely response?": ("binary", "POST-HOC outcome; rejected as target",
                         "kept for documentation only"),
    "Complaint ID": ("identifier", "primary key", "empty IDs excluded before dedup; "
                     "exact duplicate counting via 128-bit digest buckets"),
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    prof = json.loads((root / "results" / "full_profile.json").read_text(encoding="utf-8"))
    f, cols = prof["file"], {c["field"]: c for c in prof["columns"]}
    n = f["logical_rows"]

    # ---------------- data dictionary ----------------
    lines = [
        "# Data Dictionary — CFPB Consumer Complaint Database (full file)", "",
        f"Generated by `src/make_docs.py` from `results/full_profile.json` "
        f"({prof['meta']['generated_at_utc']}).",
        f"Observation unit: one complaint record. Logical records: **{n:,}**; "
        f"physical lines: **{f['physical_lines']:,}**; columns: **{f['columns']}**.",
        "",
        "| # | Field | Type | Missing (n) | Missing % | Distinct | Role / risk | Cleaning rule | Top values |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for i, name in enumerate(SCHEMA, 1):
        c = cols[name]
        typ, role, rule = ROLES[name]
        distinct = c["distinct_observed"] if c["distinct_observed"] is not None else "n/a*"
        top = "; ".join(f"{k} ({v:,})" for k, v in list(c["top_values"].items())[:3])
        top = top.replace("|", "/")[:110]
        lines.append(
            f"| {i} | `{name}` | {typ} | {c['missing']:,} | "
            f"{c['missing_rate']*100:.2f}% | {distinct} | {role} | {rule} | {top or '-'} |")
    lines += [
        "",
        "* `n/a` = high-cardinality / free-text column; exact distinct count is not "
        "accumulated (bounded accumulators). `Complaint ID` distinctness is measured "
        "exactly by `src/profile_full.py` instead.",
        "",
        "## Field boundary (leakage control)",
        "",
        "Post-hoc fields, never used as features: " +
        ", ".join(f"`{x}`" for x in POST_HOC_FIELDS) + ".",
        "",
        "## Quality summary (full file)",
        "",
        f"- Row-width mismatches: {sum(v for k, v in f['row_width_distribution'].items() if int(k) != 16):,}",
        f"- Empty Complaint IDs: {prof['ids']['empty_ids']:,}",
        f"- Duplicate Complaint IDs: {prof['ids']['duplicate_rows']:,} "
        f"({prof['ids']['duplicate_rate']:.4%}) over {prof['ids']['nonempty_ids']:,} non-empty IDs",
        f"- Invalid/missing dates: {prof['dates']['invalid_or_missing']}",
        f"- ZIP kinds: {prof['zip']['kinds']}",
        f"- Narrative present: {prof['narrative']['nonempty']:,} "
        f"({prof['narrative']['nonempty_rate']:.2%}); mean length "
        f"{prof['narrative']['mean_chars']:,} chars; "
        f"{prof['narrative']['records_with_embedded_newline']:,} contain embedded newlines",
        "",
    ]
    (root / "data" / "data_dictionary.md").write_text("\n".join(lines), encoding="utf-8")

    # ---------------- dataset card ----------------
    card = [
        "# Dataset Card — CFPB Consumer Complaint Database (Phase 2 snapshot)", "",
        "## Motivation", "",
        "The project studies whether consumer-complaint issue labels can be predicted "
        "from the narrative a consumer submits, and whether a large language model "
        "adds value over simple baselines under a leakage-free evaluation design.",
        "", "## Composition", "",
        f"- Observation unit: one complaint (`Complaint ID`). "
        f"**{n:,}** logical records, **{f['columns']}** columns.",
        f"- Physical lines **{f['physical_lines']:,}** > logical records: narratives "
        "contain quoted newlines; count logical CSV records, never physical lines.",
        f"- Date range `{prof['dates']['date_min']['Date received']}` to "
        f"`{prof['dates']['date_max']['Date received']}` "
        f"({prof['dates']['months']} calendar months).",
        f"- Target `Issue`: {prof['labels']['issue_class_count']} classes. "
        "Features: submission-time fields only.",
        f"- Sample frame for text modelling: **{prof['narrative']['nonempty_with_issue']:,}** "
        f"records with non-empty narrative and Issue; seeded reservoir of "
        f"**{prof['narrative']['reservoir_size']:,}** is used for the baselines.",
        "", "## Collection process", "",
        "- Source: Consumer Financial Protection Bureau (CFPB), Consumer Complaint "
        "Database, public download of `complaints.csv.zip` containing `complaints.csv`.",
        "- ＊TO CONFIRM BY TEAM＊: exact download URL, download date, snapshot/version "
        "identifier, and the licence / terms-of-use statement at download time.",
        "- Included population: complaints submitted to CFPB and published in the database. "
        "Excluded: consumers who never complained, unpublished records, non-US jurisdictions.",
        "", "## Preprocessing", "",
        "- Single-pass streaming decode with `newline=''`; SHA256 of the uncompressed "
        f"CSV: `{f['csv_sha256']}`.",
        "- ZIP privacy masks kept as masks; post-hoc fields separated from features; "
        "temporal 70/15/15 split frozen as SHA256-listed ID files.",
        "- Narratives normalised, truncated to 2500 chars, and PII-redacted before any "
        "external model call.",
        "", "## Uses", "",
        "- In scope: data-quality profiling, issue-label classification, baseline and "
        "LLM comparison under a fixed evaluation protocol.",
        "- Out of scope: predicting company responses from submission-time data, "
        "generating replies, causal claims about company behaviour, individual-level "
        "decisions about consumers.",
        "", "## Distribution and maintenance", "",
        "- The raw 8.9 GB file is NOT redistributed in this repository. Access method: "
        "public CFPB download (URL/date to be recorded by the team).",
        "- A small synthetic sample (`data/sample_complaints.csv`) is included for tests.",
        "- Versioning: dataset identity is the uncompressed CSV SHA256 above; any new "
        "download requires a new split and a new run of `src/run_all.py`.",
        "", "## Ethical considerations", "",
        "- Narratives are de-identified but may still contain names, account numbers "
        "and addresses; no raw narrative is published in the report.",
        "- `Tags` (servicemember / older American) and ZIP are sensitive; used only for "
        "subgroup auditing, never as predictors.",
        "- ＊TO CONFIRM BY TEAM＊: local plaintext access control and deletion policy.",
        "",
    ]
    (root / "data" / "dataset_card.md").write_text("\n".join(card), encoding="utf-8")

    # ---------------- environment lock ----------------
    pkgs = {}
    for name in ("matplotlib", "numpy", "pytest"):
        try:
            pkgs[name] = md.version(name)
        except Exception:
            pkgs[name] = "not installed (optional)"
    env = {
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "python": sys.version,
        "implementation": platform.python_implementation(),
        "platform": platform.platform(),
        "machine": platform.machine(),
        "processor": platform.processor(),
        "cpu_count": __import__("os").cpu_count(),
        "packages": pkgs,
        "core_pipeline_dependencies": "Python standard library only",
        "seed": 20261107,
        "full_profile_run": prof["meta"],
        "commands": [
            "python -m pip install -r requirements.txt",
            "python src/run_all.py --source <complaints.csv.zip> --root .",
            "python -m pytest -q",
            "python src/make_figures.py --root .",
            "python src/llm_eval.py --root . --backend mock --limit 20",
        ],
    }
    (root / "environment.json").write_text(
        json.dumps(env, ensure_ascii=False, indent=2), encoding="utf-8")

    repro = [
        "# Reproduction commands (Phase 2)", "",
        "```bash",
        "python -m pip install -r requirements.txt",
        "python src/profile_full.py --source <complaints.csv.zip> --out-dir . --sample-size 40000",
        "python src/split.py --root .",
        "python src/baselines.py --root .",
        "python src/llm_eval.py --root . --backend mock",
        "python src/make_figures.py --root .",
        "python src/make_docs.py --root .",
        "python -m pytest -q",
        "```", "",
        "Replace `--backend mock` with `--backend cache` or `--backend api` when an "
        "authorised model endpoint is available. Mock numbers are never reportable "
        "model results.", "",
        f"Full-file profile: {n:,} logical rows in "
        f"{prof['meta']['elapsed_seconds']:,} s, peak working set "
        f"{prof['meta']['peak_working_set_bytes']/2**20:,.0f} MiB.", "",
    ]
    (root / "results" / "reproduction_commands.md").write_text(
        "\n".join(repro), encoding="utf-8")
    print("[docs] wrote data_dictionary.md, dataset_card.md, environment.json, "
          "reproduction_commands.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
